// The window of the world the map shows: split in the Pacific, cropped above Greenland's
// middle and below Cape Horn.
const WEST = -170;
const NORTH = 78;
const SOUTH = -56;

export function project(lon, lat, width, height) {
  const x = ((lon - WEST + 360) % 360) / 360 * width;
  const y = (NORTH - lat) / (NORTH - SOUTH) * height;
  return [Math.round(x * 10) / 10, Math.round(y * 10) / 10];
}

function landPath(width, height) {
  return LAND.map((ring) => {
    // Rings are plotted without wrapping so the far east of Russia can run past 180 degrees.
    const points = ring.map(([lon, lat]) => {
      const x = (lon - WEST) / 360 * width;
      const y = (NORTH - lat) / (NORTH - SOUTH) * height;
      return `${Math.round(x * 10) / 10},${Math.round(y * 10) / 10}`;
    });
    return `M${points.join('L')}Z`;
  }).join('');
}

// pins: [{ n, lon, lat, color }] numbered pins; dots: [{ lon, lat, color }] small unnumbered marks.
export function worldMap({ width, height, pins, dots }) {
  const marks = dots.map(({ lon, lat, color }) => {
    const [x, y] = project(lon, lat, width, height);
    return `<circle cx="${x}" cy="${y}" r="2.6" fill="${color}" stroke="#fff" stroke-width="0.8"/>`;
  }).join('');
  const numbered = pins.map(({ n, lon, lat, color, dx = 0, dy = 0 }) => {
    const [px, py] = project(lon, lat, width, height);
    const x = px + dx;
    const y = py + dy;
    const leader = dx || dy ? `<line x1="${px}" y1="${py}" x2="${x}" y2="${y}" stroke="${color}" stroke-width="1"/><circle cx="${px}" cy="${py}" r="1.6" fill="${color}"/>` : '';
    return `${leader}<circle cx="${x}" cy="${y}" r="7" fill="${color}" stroke="#fff" stroke-width="1.2"/>` +
      `<text x="${x}" y="${y + 3.2}" text-anchor="middle" font-family="DejaVu Sans Condensed, DejaVu Sans, sans-serif" font-weight="700" font-size="${n > 9 ? 8.2 : 9}" fill="#fff">${n}</text>`;
  }).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}">` +
    `<rect width="${width}" height="${height}" fill="#dbe7ee"/>` +
    `<path d="${landPath(width, height)}" fill="#c9bfa5" stroke="#a89d80" stroke-width="0.6" stroke-linejoin="round"/>` +
    marks + numbered + '</svg>';
}
